create table if not exists staff_tables (
  id text primary key,
  label text not null,
  minimum_spend_eur integer not null default 0 check (minimum_spend_eur >= 0),
  map_x numeric(5,2) not null default 50 check (map_x between 0 and 100),
  map_y numeric(5,2) not null default 50 check (map_y between 0 and 100),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table staff_tables enable row level security;

create table if not exists staff_table_assignments (
  event_key text not null,
  rsvp_id bigint not null references public.rsvps(id) on delete cascade,
  table_id text not null references public.staff_tables(id) on delete cascade,
  assigned_at timestamptz not null default now(),
  primary key (event_key, rsvp_id)
);
alter table staff_table_assignments enable row level security;

create table if not exists staff_users (
  id uuid primary key default gen_random_uuid(),
  username text not null,
  password_hash text not null,
  role text not null check (role in ('owner', 'admin', 'door', 'service')),
  active boolean not null default true,
  failed_login_count integer not null default 0,
  locked_until timestamptz,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists staff_users_username_unique
  on staff_users (lower(username));
alter table staff_users enable row level security;

create table if not exists staff_sessions (
  id uuid primary key default gen_random_uuid(),
  staff_user_id uuid not null references public.staff_users(id) on delete cascade,
  session_token_hash text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz
);
create unique index if not exists staff_sessions_token_hash_unique
  on staff_sessions (session_token_hash);
create index if not exists staff_sessions_user_idx
  on staff_sessions (staff_user_id);
create index if not exists staff_sessions_expires_idx
  on staff_sessions (expires_at);
alter table staff_sessions enable row level security;

