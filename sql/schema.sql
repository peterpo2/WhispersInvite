create table if not exists guest_list (
  id text primary key,
  name text not null,
  email text,
  phone text,
  ticket_token text,
  confirmation_email_sent_at timestamptz,
  confirmation_email_send_count integer not null default 0,
  created_at timestamptz default now(),
  updated_at timestamptz not null default now()
);

create table if not exists rsvps (
  id bigint generated by default as identity primary key,
  event_key text not null,
  guest_id text not null,
  guest_name text not null,
  guest_email text,
  guest_phone text,
  status text not null check (status in ('attending','declined')),
  plus_one_name text,
  plus_one_email text,
  plus_one_phone text,
  plus_one_email_is_fallback boolean not null default false,
  wants_table_reservation boolean not null default false,
  reservation_confirmed boolean not null default false,
  seal_code text,
  confirmation_token text,
  ticket_token text,
  checked_in_at timestamptz,
  plus_one_ticket_token text,
  plus_one_seal_code text,
  plus_one_checked_in_at timestamptz,
  ticket_email_sent_at timestamptz,
  submitted_at timestamptz default now(),
  unique(event_key, guest_id)
);

create index if not exists guest_list_name_idx on guest_list using gin (to_tsvector('simple', name));
create unique index if not exists guest_list_ticket_token_unique
  on guest_list (ticket_token)
  where ticket_token is not null;
create unique index if not exists rsvps_event_plus_one_email_unique
  on rsvps (event_key, lower(plus_one_email))
  where plus_one_email is not null;
create unique index if not exists rsvps_event_seal_code_unique
  on rsvps (event_key, seal_code)
  where seal_code is not null;
create unique index if not exists rsvps_ticket_token_unique
  on rsvps (ticket_token)
  where ticket_token is not null;
create unique index if not exists rsvps_confirmation_token_unique
  on rsvps (confirmation_token)
  where confirmation_token is not null;
create index if not exists rsvps_checked_in_at_idx on rsvps (checked_in_at);
create index if not exists rsvps_contact_lookup_idx
  on rsvps (event_key, guest_email, guest_phone)
  where guest_email is not null and guest_phone is not null;
create index if not exists rsvps_ticket_email_pending_idx
  on rsvps (event_key, ticket_email_sent_at)
  where status = 'attending' and ticket_token is not null;
create unique index if not exists rsvps_plus_one_ticket_token_unique
  on rsvps (plus_one_ticket_token)
  where plus_one_ticket_token is not null;
create unique index if not exists rsvps_event_plus_one_seal_code_unique
  on rsvps (event_key, plus_one_seal_code)
  where plus_one_seal_code is not null;

create table if not exists rsvp_companions (
  id bigint generated by default as identity primary key,
  rsvp_id bigint not null references public.rsvps(id) on delete cascade,
  guest_name text not null,
  email text,
  email_is_fallback boolean not null default false,
  phone text not null,
  confirmation_token text,
  ticket_token text,
  seal_code text,
  checked_in_at timestamptz,
  ticket_email_sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists rsvp_companions_ticket_token_unique
  on rsvp_companions (ticket_token)
  where ticket_token is not null;
create unique index if not exists rsvp_companions_confirmation_token_unique
  on rsvp_companions (confirmation_token)
  where confirmation_token is not null;
create unique index if not exists rsvp_companions_seal_code_unique
  on rsvp_companions (seal_code)
  where seal_code is not null;
create index if not exists rsvp_companions_email_pending_idx
  on rsvp_companions (ticket_email_sent_at)
  where ticket_token is not null;
alter table rsvp_companions enable row level security;

